"""Проверка свободных тем/поручений на подготовку вреда.

Свобода интересов максимальная: Nexus не решает, что «правильно» изучать. Запрещена только
ПОДГОТОВКА ВРЕДА конкретным людям, включая самого человека, а не тема как таковая
(«история терактов» можно, «как собрать бомбу» нельзя).

Решение в три шага:
  1. Дешёвые правила — только самые однозначные обороты (глагол действия + конкретный опасный объект:
     «как изготовить бомбу», явный запрос способа самоубийства). Срабатывают редко, но наверняка,
     и без модели — её можно и не звать.
  2. Если правила не сработали — модель отвечает на узкий вопрос по уже готовым критериям:
     это изучение темы или подготовка вреда? Критерии задаёт код, не модель.
  3. Код комбинирует: правило DENY — всегда запрет; иначе ответ модели. При сомнении (кривой ответ
     модели и т. п.) — ASK, переспросить человека, а не молчаливый отказ.

Это самостоятельный модуль без обращения к движку: вызывающий код сам решает, как спросить модель
(учитывая занятость приоритетной программы), и передаёт сюда только готовый ответ или функцию для его получения.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass

ALLOW, ASK, DENY = "allow", "ask", "deny"

# Узкие, однозначные обороты: глагол действия + конкретный опасный объект.
# Сами по себе слова «бомба», «наркотик» не ловятся — читать про них можно.
_DENY_PATTERNS = [
    (re.compile(r"как\s+(сделать|изготовить|собрать|синтезировать)\s+\S*\s*(бомб|взрывчат|\bмину\b|гранат)", re.I),
     "инструкция по взрывному устройству"),
    (re.compile(r"как\s+(сделать|получить|синтезировать|сварить|приготовить)\s+\S*\s*"
               r"(наркотик|мефедрон|метамфетамин|героин|фентанил)", re.I), "синтез наркотиков"),
    (re.compile(r"способ\w*\s+самоубийств|как\s+(покончить с собой|совершить суицид)", re.I),
     "способ самоубийства"),
]

VERDICT_SCHEMA = {
    "type": "object",
    "properties": {
        "verdict": {"type": "string", "enum": [ALLOW, ASK, DENY]},
        "why": {"type": "string"},
    },
    "required": ["verdict", "why"],
}

_PROMPT = (
    "Ты определяешь, можно ли помогать человеку с этим запросом. Свобода интересов максимальная: "
    "любые темы, даже мрачные, взрослые или спорные, разрешены — это личный интерес человека, не твоя оценка морали.\n"
    "Запрещена ТОЛЬКО подготовка реального вреда конкретным людям, включая самого человека: "
    "как сделать оружие или взрывчатку; синтез наркотиков; как напасть или навредить конкретному человеку "
    "или себе (включая способы самоубийства); слежка за конкретным человеком; поиск уязвимых людей "
    "(например, детей без присмотра) с целью им навредить; сексуальный контент с детьми или животными.\n"
    "Изучение темы как явления — история, наука, политика, психология, культура — это НЕ подготовка вреда, "
    "даже если тема мрачная (история терактов, наркополитика, психология суицида изучать можно).\n\n"
    'Запрос человека: "{text}"\n\n'
    f'Ответь verdict: "{ALLOW}" (обычный интерес или изучение темы), "{DENY}" (явная подготовка вреда конкретным '
    f'людям) или "{ASK}" (неясно, нужно уточнение у человека). why — одно короткое предложение по-русски.')


@dataclass
class Verdict:
    decision: str           # allow | ask | deny
    reason: str
    source: str              # "правило" | "модель"


def cheap_check(text: str) -> Verdict | None:
    for pat, reason in _DENY_PATTERNS:
        if pat.search(text):
            return Verdict(DENY, reason, "правило")
    return None


def model_messages(text: str) -> list[dict]:
    return [{"role": "system", "content": "Отвечай только по-русски, только JSON."},
            {"role": "user", "content": _PROMPT.format(text=text[:1000])}]


def parse_verdict(raw: str) -> Verdict:
    d = json.loads(raw)
    v = d["verdict"]
    if v not in (ALLOW, ASK, DENY):
        raise ValueError(f"неизвестный verdict: {v!r}")
    return Verdict(v, str(d.get("why", "")).strip()[:300], "модель")


def classify(text: str, ask_model) -> Verdict:
    """ask_model(messages) -> сырой ответ модели (строка JSON). Если сработало дешёвое правило,
    модель вообще не зовётся."""
    cheap = cheap_check(text)
    if cheap is not None:
        return cheap
    try:
        return parse_verdict(ask_model(model_messages(text)))
    except (ValueError, KeyError, TypeError, json.JSONDecodeError):
        return Verdict(ASK, "не удалось разобрать ответ модели — лучше уточнить у человека", "модель")
